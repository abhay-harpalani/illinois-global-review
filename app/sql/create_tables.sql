CREATE TABLE articles (
    article_id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    creation_date_epoch TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    edit_date_epoch TIMESTAMPTZ NOT NULL,
    cover_image_path TEXT NOT NULL,
    cover_image_alt_text TEXT,
    cover_image_source TEXT,
    citation TEXT,
    body TEXT NOT NULL
);

CREATE TABLE tags (
    slug TEXT PRIMARY KEY,
    display_name TEXT NOT NULL
);

CREATE TABLE article_tags (
    article_id INT REFERENCES articles(article_id) ON UPDATE CASCADE ON DELETE CASCADE,
    tag_slug TEXT REFERENCES tags(slug) ON UPDATE CASCADE ON DELETE CASCADE,

    PRIMARY KEY (article_id, tag_slug)
);
